def get_all_index_companies() -> list[dict]:
    """Return all companies from all indices as a flat list with index tag."""
    companies = []
    for index_id, info in INDEX_REGISTRY.items():
        for c in info["companies"]:
            asset_type = "stock"
            if index_id == "crypto":
                asset_type = "crypto"
            elif index_id == "commodities":
                asset_type = "commodity"
            elif index_id == "etfs":
                asset_type = "etf"
            elif index_id == "funds":
                asset_type = "fund"
            companies.append({
                **c,
                "index": info["name"],
                "index_id": index_id,
                "asset_type": asset_type,
            })
    return companies


def search_companies(query: str, index_filter: str | None = None) -> list[dict]:
    """Search companies by name, ticker or ISIN. Returns max 50 results."""
    all_companies = get_all_index_companies()
    query_lower = query.lower().strip()

    if not query_lower:
        if index_filter:
            return [c for c in all_companies if c["index"] == index_filter]
        return all_companies

    results = []
    for c in all_companies:
        if index_filter and c["index"] != index_filter:
            continue
        if (query_lower in c["ticker"].lower()
                or query_lower in c["name"].lower()
                or query_lower in c.get("isin", "").lower()):
            results.append(c)

    return results[:50]


def search_by_isin(isin: str) -> dict | None:
    """Search for a company by its exact ISIN code."""
    isin_upper = isin.upper().strip()
    for c in get_all_index_companies():
        if c.get("isin", "").upper() == isin_upper:
            return c
    return None
